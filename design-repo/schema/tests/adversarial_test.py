#!/usr/bin/env python3
"""Adversarial suite: prove every rule actually rejects a bad instance.

Two halves, and both matter equally:

CONTROLS — one minimal valid PageSpec synthesized generically from every
template's own node list, plus the bundled example. All must produce ZERO
errors. A validator that rejects everything is as broken as one that rejects
nothing, and because the controls are generated by iterating
templates/templates.json rather than hand-written, adding a 23rd template
auto-covers it with no new control code.

MUTATIONS — one deliberately broken spec per rule, each of which MUST be
rejected. Grouped by layer: schema, structural, runtime, compliance.

Run:  python3 schema/tests/adversarial_test.py
"""

from __future__ import annotations

import copy
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(REPO, "schema"))

import semantic_validate as sv  # noqa: E402

try:
    from jsonschema import Draft7Validator
except ImportError:  # pragma: no cover
    print("FATAL: jsonschema is not installed (pip install jsonschema)")
    sys.exit(2)

SCHEMA = json.load(open(os.path.join(REPO, "schema", "pagespec.schema.json")))
VALIDATOR = Draft7Validator(SCHEMA)
TEMPLATES = json.load(
    open(os.path.join(REPO, "templates", "templates.json")))["templates"]
SECTIONS = sv.load_sections()
EXAMPLE_PATH = os.path.join(REPO, "schema", "example.pagespec.json")
EXAMPLE = json.load(open(EXAMPLE_PATH))

SETTABLE_MOTION = sv.SETTABLE_MOTION


def schema_errors(spec) -> list[str]:
    return [e.message for e in VALIDATOR.iter_errors(spec)]


def all_errors(spec) -> list[str]:
    """Both layers. A spec is valid only if BOTH produce nothing."""
    return schema_errors(spec) + sv.validate(spec).errors


ROUTE_MAP = json.load(
    open(os.path.join(REPO, "templates", "route-map.json")))["map"]

# Reverse the real route map once: template id -> its first real route.
# templates.json carries no `routes` field — routes live in route-map.json, so
# deriving them from the template entry silently yields "/" for everything and
# makes every route-scoped rule misfire.
_FIRST_ROUTE: dict[str, str] = {}
for _route, _tid in sorted(ROUTE_MAP.items()):
    _FIRST_ROUTE.setdefault(_tid, _route)


def route_for(tid: str) -> str:
    """A REAL route for this template, so route-scoped rules behave."""
    if tid not in _FIRST_ROUTE:
        raise AssertionError(
            f"{tid} has no route in templates/route-map.json — route coverage "
            "is not 1:1 with the template list")
    return _FIRST_ROUTE[tid]


def synth(tid: str) -> dict:
    """Minimal valid PageSpec for a template, built from its OWN node list."""
    t = TEMPLATES[tid]
    nodes = []
    for n in t["nodes"]:
        nid = n["section"]
        contract = SECTIONS[nid]
        node = {
            "section": nid,
            "required": n["required"],
            "repeatable": n["repeatable"],
        }
        if "variant" in n:
            node["variant"] = n["variant"]
        real = contract.get("motion") or {}
        node["motion"] = {k: real[k] for k in SETTABLE_MOTION if k in real}
        nodes.append(node)
    return {
        "pageSpecVersion": "1.0.0",
        "route": route_for(tid),
        "template": tid,
        "nodes": nodes,
    }


# ── mutations ────────────────────────────────────────────────────────────────

def mutate_unknown_template(_):
    s = copy.deepcopy(EXAMPLE); s["template"] = "T-DOES-NOT-EXIST"; return s


def mutate_missing_required_field(_):
    s = copy.deepcopy(EXAMPLE); del s["route"]; return s


def mutate_invented_section(_):
    s = copy.deepcopy(EXAMPLE)
    s["nodes"][2]["section"] = "hero.totally-invented"
    return s


def mutate_invented_root_field(_):
    s = copy.deepcopy(EXAMPLE); s["seoScore"] = 99; return s


def mutate_drop_reduced_motion(_):
    s = copy.deepcopy(EXAMPLE)
    s["nodes"][0]["motion"].pop("reducedMotionFallback", None)
    return s


def mutate_invented_motion_field(_):
    s = copy.deepcopy(EXAMPLE)
    s["nodes"][0]["motion"]["inventedAnimation"] = "zoomBlast"
    return s


def mutate_swap_motion_pattern(_):
    s = copy.deepcopy(EXAMPLE)
    for n in s["nodes"]:
        if n["section"] == "divider.leaf-band":
            n["motion"]["pattern"] = "overlay-slide"
    return s


def mutate_add_stagger(_):
    s = copy.deepcopy(EXAMPLE)
    for n in s["nodes"]:
        if n["section"] == "divider.leaf-band":
            n["motion"]["staggerMs"] = 80
    return s


def mutate_unknown_asset_role(_):
    s = copy.deepcopy(EXAMPLE)
    s["nodes"][2]["assetRefs"] = [{"assetRole": "person.deepfake"}]
    return s


def mutate_duplicate_one_per_page(_):
    """conversion.lead-magnet-cta is not repeatable on T-ARTICLE."""
    s = copy.deepcopy(EXAMPLE)
    dup = next(n for n in s["nodes"] if n["section"] == "conversion.lead-magnet-cta")
    s["nodes"].insert(s["nodes"].index(dup), copy.deepcopy(dup))
    return s


def mutate_remove_mandatory(_):
    s = copy.deepcopy(EXAMPLE)
    s["nodes"] = [n for n in s["nodes"] if n["section"] != "hero.page-head"]
    return s


def mutate_reorder_fixed_position(_):
    """Move the footer out of its closing position."""
    s = copy.deepcopy(EXAMPLE)
    footer = next(n for n in s["nodes"] if n["section"] == "chrome.footer")
    s["nodes"].remove(footer)
    s["nodes"].insert(2, footer)
    return s


def mutate_template_node_mismatch(_):
    """Declare T-LEGAL but keep T-ARTICLE's nodes. The single most repeated
    bug class in prior builds: a spec contradicting its own template."""
    s = copy.deepcopy(EXAMPLE)
    s["template"] = "T-LEGAL"
    s["route"] = "/privacy-policy"
    return s


def mutate_foreign_section(_):
    """hero.home is restricted to T-HOME by its own contract."""
    s = copy.deepcopy(EXAMPLE)
    home = SECTIONS["hero.home"]
    real = home.get("motion") or {}
    s["nodes"].insert(3, {
        "section": "hero.home", "required": True, "repeatable": False,
        "motion": {k: real[k] for k in SETTABLE_MOTION if k in real},
    })
    return s


def mutate_banner_on_wrong_route(_):
    """The banner is measured only on / and /blog/:slug."""
    s = copy.deepcopy(EXAMPLE)
    s["route"] = "/pricing"
    s["template"] = "T-PRICING"
    return s


def mutate_max_words_overflow(_):
    s = copy.deepcopy(EXAMPLE)
    for n in s["nodes"]:
        if n["section"] == "hero.page-head":
            n["content"]["h1"] = " ".join(["word"] * 60)
    return s


MUTATIONS = [
    ("schema",     "unknown template enum value",        mutate_unknown_template),
    ("schema",     "missing required root field",        mutate_missing_required_field),
    ("schema",     "invented section id",                mutate_invented_section),
    ("schema",     "invented root property",             mutate_invented_root_field),
    ("schema",     "missing reducedMotionFallback",      mutate_drop_reduced_motion),
    ("schema",     "invented motion field",              mutate_invented_motion_field),
    ("schema",     "unknown assetRole",                  mutate_unknown_asset_role),
    ("structural", "swapped motion pattern",             mutate_swap_motion_pattern),
    ("structural", "added stagger where measured is 0",  mutate_add_stagger),
    ("structural", "duplicated non-repeatable section",  mutate_duplicate_one_per_page),
    ("structural", "removed mandatory section",          mutate_remove_mandatory),
    ("structural", "reordered fixed-position section",   mutate_reorder_fixed_position),
    ("structural", "template / node-sequence mismatch",  mutate_template_node_mismatch),
    ("structural", "section used outside allowedTemplates", mutate_foreign_section),
    ("structural", "banner on a non-banner route",       mutate_banner_on_wrong_route),
    ("runtime",    "maxWords overflow on a real field",  mutate_max_words_overflow),
]


def main() -> int:
    failures: list[str] = []

    print("CONTROLS (must all pass with zero errors)")
    errs = all_errors(EXAMPLE)
    if errs:
        failures.append(f"bundled example produced {len(errs)} error(s): {errs[:3]}")
        print(f"  FAIL  example.pagespec.json -> {len(errs)} error(s)")
        for e in errs[:5]:
            print(f"          {e}")
    else:
        print("  ok    example.pagespec.json")

    for tid in sorted(TEMPLATES):
        spec = synth(tid)
        errs = all_errors(spec)
        if errs:
            failures.append(f"synthesized control for {tid}: {errs[:2]}")
            print(f"  FAIL  {tid} -> {len(errs)} error(s)")
            for e in errs[:4]:
                print(f"          {e}")
        else:
            print(f"  ok    {tid}")

    print(f"\nMUTATIONS (must all be REJECTED) — {len(MUTATIONS)} cases")
    for layer, name, fn in MUTATIONS:
        spec = fn(None)
        errs = all_errors(spec)
        if errs:
            print(f"  ok    [{layer}] {name} -> rejected ({len(errs)})")
        else:
            failures.append(f"mutation NOT rejected: [{layer}] {name}")
            print(f"  FAIL  [{layer}] {name} -> ACCEPTED (should have been rejected)")

    print()
    if failures:
        print(f"RESULT: {len(failures)} failure(s)")
        for f in failures:
            print(f"  - {f}")
        return 1
    print(f"RESULT: all {len(TEMPLATES) + 1} controls pass, "
          f"all {len(MUTATIONS)} mutations rejected")
    return 0


if __name__ == "__main__":
    sys.exit(main())
