#!/usr/bin/env python3
"""Adversarial suite: prove every rule actually rejects a bad instance.

Two halves, and both matter equally:

CONTROLS — one minimal valid PageSpec synthesized generically from every
template's own node list, plus the bundled example. All must produce ZERO
errors. A validator that rejects everything is as broken as one that rejects
nothing, and because the controls are generated by iterating
templates/templates.json rather than hand-written, adding a 23rd template
auto-covers it with no new control code.

MUTATIONS — one deliberately broken spec per rule, each of which MUST be
rejected. Grouped by layer: schema, structural, runtime, compliance.

Run:  python3 schema/tests/adversarial_test.py
"""

