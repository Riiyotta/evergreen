HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(REPO, "schema"))

import semantic_validate as sv  # noqa: E402

try:
    from jsonschema import Draft7Validator
except ImportError:  # pragma: no cover
    print("FATAL: jsonschema is not installed (pip install jsonschema)")
    sys.exit(2)

SCHEMA = json.load(open(os.path.join(REPO, "schema", "pagespec.schema.json")))
VALIDATOR = Draft7Validator(SCHEMA)
TEMPLATES = json.load(
    open(os.path.join(REPO, "templates", "templates.json")))["templates"]
SECTIONS = sv.load_sections()
EXAMPLE_PATH = os.path.join(REPO, "schema", "example.pagespec.json")
EXAMPLE = json.load(open(EXAMPLE_PATH))

SETTABLE_MOTION = sv.SETTABLE_MOTION


def schema_errors(spec) -> list[str]:
    return [e.message for e in VALIDATOR.iter_errors(spec)]


def all_errors(spec) -> list[str]:
    """Both layers. A spec is valid only if BOTH produce nothing."""
    return schema_errors(spec) + sv.validate(spec).errors


ROUTE_MAP = json.load(
    open(os.path.join(REPO, "templates", "route-map.json")))["map"]

# Reverse the real route map once: template id -> its first real route.
# templates.json carries no `routes` field — routes live in route-map.json, so
# deriving them from the template entry silently yields "/" for everything and
# makes every route-scoped rule misfire.
_FIRST_ROUTE: dict[str, str] = {}
for _route, _tid in sorted(ROUTE_MAP.items()):
    _FIRST_ROUTE.setdefault(_tid, _route)


def route_for(tid: str) -> str:
    """A REAL route for this template, so route-scoped rules behave."""
    if tid not in _FIRST_ROUTE:
        raise AssertionError(
            f"{tid} has no route in templates/route-map.json — route coverage "
            "is not 1:1 with the template list")
    return _FIRST_ROUTE[tid]


def neutral_route(tid: str) -> str:
    """A generation-mode route: the real route's first segment, with any real
    slug replaced. The real slugs are source copy / customer names, and the
    generation rules (correctly) reject them."""
    segs = [s for s in route_for(tid).split("/") if s]
    return "/" + "/".join(segs[:1] + ["example-page"] * (len(segs) > 1)) if segs else "/"


def synth(tid: str, mode: str = "clone") -> dict:
    """Minimal valid PageSpec for a template, built from its OWN node list."""
    t = TEMPLATES[tid]
    nodes = []
    for n in t["nodes"]:
        nid = n["section"]
        contract = SECTIONS[nid]
        node = {
            "section": nid,
            "required": n["required"],
            "repeatable": n["repeatable"],
        }
        if "variant" in n:
            node["variant"] = n["variant"]
        real = contract.get("motion") or {}
        node["motion"] = {k: real[k] for k in SETTABLE_MOTION if k in real}
        nodes.append(node)
    return {
        "pageSpecVersion": "2.0.0",
        "mode": mode,
        "route": route_for(tid) if mode == "clone" else neutral_route(tid),
        "template": tid,
        "nodes": nodes,
    }


